type SeedLine = {
  description: string;
  sku: string;
  quantityMilli: bigint;
  unitPriceMinor: bigint;
  taxRateBps?: number;
};

type InsertedInvoice = {
  id: string;
  invoiceNumber: string;
  vendorId: string;
  currency: string;
  lines: SeedLine[];
  totalMinor: bigint;
};

type InsertedReceipt = {
  id: string;
  receiptNumber: string;
};

function daysAgo(days: number): Date {
  return new Date(Date.now() - days * 24 * 60 * 60 * 1000);
}

function isoDaysAgo(days: number): string {
  return daysAgo(days).toISOString().slice(0, 10);
}

function lineSubtotal(lines: SeedLine[]): bigint {
  return lines.reduce(
    (sum, line) => sum + computeLineTotal(line.unitPriceMinor, line.quantityMilli),
    0n,
  );
}

function lineTax(lines: SeedLine[]): bigint {
  return lines.reduce(
    (sum, line) =>
      sum +
      computeTax(
        computeLineTotal(line.unitPriceMinor, line.quantityMilli),
        line.taxRateBps ?? 0,
      ),
    0n,
  );
}

