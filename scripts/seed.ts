    proposedAmount: "50000.00",
    disputedAmount: "10000.00",
    reason:
      "Commercial proposal based on the purchase-order unit price of INR 2,500 for 20 received units. The INR 10,000 variance is flagged exposure, not a conclusion that the vendor owes it.",
