async function seedDocuments(input: {
  ctx: AuthContext;
  invoice: InsertedInvoice;
  po: { id: string; poNumber: string };
  poLines: SeedLine[];
  receipt: InsertedReceipt;
  receiptLines: { receivedMilli: bigint; damagedMilli: bigint; line: SeedLine }[];
  vendorName: string;
  invoiceDate: string;
  orderDate: string;
}) {
  const db = await getDb();
  const { ctx, invoice, po, poLines, receipt, receiptLines, vendorName } = input;
  const money = (value: bigint) => formatMinorPlain(value, invoice.currency);

  const invoicePdf = await makePdf(`Invoice ${invoice.invoiceNumber}`, [
    `# Vendor`,
    vendorName,
    "",
    `# Invoice details`,
    `Invoice number: ${invoice.invoiceNumber}`,
    `Issue date: ${input.invoiceDate}`,
    `Currency: ${invoice.currency}`,
    `Purchase order: ${po.poNumber}`,
    "",
    "# Lines",
    ...invoice.lines.map(
      (line, index) =>
        `${index + 1}. ${line.description} | ${line.sku} | qty ${Number(line.quantityMilli) / 1000} | unit ${money(line.unitPriceMinor)} | total ${money(computeLineTotal(line.unitPriceMinor, line.quantityMilli))}`,
    ),
    "",
    `Subtotal: ${money(lineSubtotal(invoice.lines))}`,
    `Tax: ${money(lineTax(invoice.lines))}`,
    `Total: ${money(invoice.totalMinor)}`,
    "",
    "Status: VERIFIED in the demo seed. A human reviewer is recorded.",
  ]);
  const invoiceDoc = await attachDocument({
    ctx,
    buffer: invoicePdf,
    fileName: `${invoice.invoiceNumber}.pdf`,
    title: `Invoice source document - ${invoice.invoiceNumber}`,
    documentType: "INVOICE",
    entityType: "INVOICE",
    entityId: invoice.id,
  });
  await db
    .update(invoices)
    .set({ sourceDocumentId: invoiceDoc.id })
    .where(eq(invoices.id, invoice.id));

  const poPdf = await makePdf(`Purchase order ${po.poNumber}`, [
    `# Vendor`,
    vendorName,
    "",
    `# Order details`,
    `PO number: ${po.poNumber}`,
    `Order date: ${input.orderDate}`,
    `Currency: ${invoice.currency}`,
    "",
    "# Lines",
    ...poLines.map(
      (line, index) =>
        `${index + 1}. ${line.description} | ${line.sku} | qty ${Number(line.quantityMilli) / 1000} | unit ${money(line.unitPriceMinor)} | total ${money(computeLineTotal(line.unitPriceMinor, line.quantityMilli))}`,
    ),
    "",
    `Total: ${money(lineSubtotal(poLines) + lineTax(poLines))}`,
  ]);
  await attachDocument({
    ctx,
    buffer: poPdf,
    fileName: `${po.poNumber}.pdf`,
    title: `Purchase order - ${po.poNumber}`,
    documentType: "PURCHASE_ORDER",
    entityType: "PURCHASE_ORDER",
    entityId: po.id,
  });

  const receiptPdf = await makePdf(`Goods receipt ${receipt.receiptNumber}`, [
    `# Order`,
    `Purchase order: ${po.poNumber}`,
    `Vendor: ${vendorName}`,
    "",
    "# Received quantities",
    ...receiptLines.map(
      (row, index) =>
        `${index + 1}. ${row.line.description} | received ${Number(row.receivedMilli) / 1000} | damaged ${Number(row.damagedMilli) / 1000} | usable ${(Number(row.receivedMilli) - Number(row.damagedMilli)) / 1000}`,
    ),
    "",
    "Inspection completed. This document records quantities, not a payment decision.",
  ]);
  await attachDocument({
    ctx,
    buffer: receiptPdf,
    fileName: `${receipt.receiptNumber}.pdf`,
    title: `Goods receipt - ${receipt.receiptNumber}`,
    documentType: "GOODS_RECEIPT",
    entityType: "GOODS_RECEIPT",
    entityId: receipt.id,
  });

  await recordEvidenceEvent({
    organizationId: ctx.organization.id,
    entityType: "INVOICE",
    entityId: invoice.id,
    eventType: "INVOICE_VERIFIED",
    description: `Demo invoice ${invoice.invoiceNumber} verified by a human reviewer after source-document review.`,
    actor: actorFromContext(ctx),
    source: "demo_seed",
  });
  await writeAudit({
    organizationId: ctx.organization.id,
    actor: actorFromContext(ctx),
    action: "INVOICE_VERIFIED",
    entityType: "invoice",
    entityId: invoice.id,
    description: `Seeded verified invoice ${invoice.invoiceNumber}`,
    metadata: {
      seeded: true,
      totalMinor: invoice.totalMinor.toString(),
      currency: invoice.currency,
    },
  });
}

